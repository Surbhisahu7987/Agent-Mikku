"""
This module provides tools for the Master Orchestrator Agent to manage high-level operations.
It includes tools for resolving delivery addresses, formatting menu cards, 
and delegating complex tasks to specialized sub-agents.
"""
from langchain.tools import tool
from langgraph.prebuilt.tool_node import ToolRuntime
from utils.logger import logger

@tool
def resolve_delivery_context(saved_addresses: list[dict], user_hint: str = None) -> dict:
    """
    Analyzes saved addresses and matches them against user hints to determine delivery location.
    
    Args:
        saved_addresses (list[dict]): List of address objects from the user's profile.
        user_hint (str, optional): A keyword like 'Home' or 'Work' to filter addresses. 
            Defaults to None.

    Returns:
        dict: A dictionary containing the resolution status and the selected address.
            - SUCCESS: Address found and selected.
            - REQUEST_NEW_LOCATION: No matching or saved addresses found.
    """
    if not saved_addresses:
        return {"status": "REQUEST_NEW_LOCATION", "message": "No saved addresses found."}
    
    if user_hint:
        # Simple keyword matching for 'Home', 'Work', etc.
        for addr in saved_addresses:
            if user_hint.lower() in addr.get('address_type', '').lower():
                return {"status": "SUCCESS", "address": addr}
    
    # Default to first address
    return {"status": "SUCCESS", "address": saved_addresses[0]}

@tool
def format_restaurant_menu_card(restaurant_list: list[dict]) -> str:
    """
    Transforms a list of restaurants into a clean, readable string for user display.

    Args:
        restaurant_list (list[dict]): A list of restaurant objects containing name, rating, etc.

    Returns:
        str: A formatted "Menu Card" string featuring the top recommendations.
    """
    output = "Top 5 Recommendations for you:\n"
    for i, res in enumerate(restaurant_list, 1):
        output += (
            f"{i}. {res['name']} ({res['rating']}⭐)\n"
            f"    Time: {res['delivery_time']} mins | 💰 Price for one: ₹{res['avg_price']}\n"
            f"    Delivery Fee: ₹{res.get('delivery_fee', 0)}\n"
        )
    return output

@tool(description="Order from Instamart")
async def manage_instamart_order(request: str) -> str:
    """
    Delegates grocery, recipe, or household item tasks to the specialized InstaMart agent.

    Args:
        request (str): The full user request detailing what to shop for or cook.

    Returns:
        str: The response generated by the InstaMart sub-agent.
    """
    # Lazy initialization prevents resource-heavy instantiation at import time.
    from agents.instamart_subagent import get_instamart_agent
    logger.info("Invoking Instamart agent to handle the request.")
    model_params = {
            "max_retries": 3
        }
    try:
        agent = await get_instamart_agent(model_params=model_params)
        # Using the high-level method which handles .invoke() internally
        return await agent.generate_response(request)
    
    except Exception as e:
        logger.error(f"Error occurred while initializing Instamart agent: {e}")
        raise e


@tool(description="Order from Swiggy")
async def manage_swiggy_order(request: str) -> str:
    """
    Delegates restaurant discovery and food delivery tasks to the specialized Swiggy agent.
    This function is used to manage swiggy orders. 
    Useful for ordering prepared food from restaurants or checking menus.
    Input should be the user's full request regarding food delivery.

    Args:
        request (str): The user's query regarding restaurant food or menus.

    Returns:
        str: The response generated by the Swiggy sub-agent.
    """

    from agents.swiggy_subagent import get_swiggy_agent
    model_params= {
            "max_retries": 3
        }
    try:
        agent = await get_swiggy_agent(model_params=model_params)
        response = await agent.generate_response(request)
        return response
    except Exception as e:
        logger.error(f"Error occurred while initializing Swiggy agent: {e}")
        raise e

